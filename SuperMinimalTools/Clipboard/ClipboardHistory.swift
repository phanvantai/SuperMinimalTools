import Foundation
import AppKit
import Carbon.HIToolbox
import Observation

nonisolated struct ClipboardItem: Identifiable, Codable, Equatable {
    let id: UUID
    let text: String
    let copiedAt: Date
    /// The app that was frontmost when the text was copied.
    let sourceBundleID: String?
}

/// Remembers the text the user copies so it can be copied again later.
///
/// Opt-in: nothing is watched or stored until the user enables it from the
/// dropdown, and turning it off deletes the history. Text that password
/// managers mark as concealed or transient is never recorded. The history is
/// kept in Application Support so it survives a relaunch.
@Observable
@MainActor
final class ClipboardHistory {

    static let maxItems = 200
    /// Bigger copies (logs, whole files) are skipped rather than stored.
    static let maxTextBytes = 512 * 1024

    private(set) var items: [ClipboardItem] = []

    var isEnabled: Bool {
        didSet {
            defaults.set(isEnabled, forKey: Self.isEnabledKey)
            applyEnabled()
            if !isEnabled {
                clear()
            }
        }
    }

    private static let isEnabledKey = "clipboardHistoryEnabled"
    /// Markers from nspasteboard.org that password managers and other apps set
    /// on content that shouldn't end up in a clipboard history.
    private nonisolated static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    private let defaults: UserDefaults
    private let storageURL: URL
    @ObservationIgnored private var lastChangeCount = 0
    @ObservationIgnored private var monitorTask: Task<Void, Never>?
    @ObservationIgnored private var hotKey: GlobalHotKey?
    @ObservationIgnored private lazy var panel = ClipboardPanel(history: self)

    init(defaults: UserDefaults = .standard, storageURL: URL = ClipboardHistory.defaultStorageURL) {
        self.defaults = defaults
        self.storageURL = storageURL
        isEnabled = defaults.bool(forKey: Self.isEnabledKey)
        load()
        applyEnabled()
    }

    nonisolated static var defaultStorageURL: URL {
        URL.applicationSupportDirectory
            .appending(path: Bundle.main.bundleIdentifier ?? "SuperMinimalTools")
            .appending(path: "clipboard-history.json")
    }

    nonisolated static func shouldRecord(types: [NSPasteboard.PasteboardType]) -> Bool {
        types.contains(.string) && ignoredTypes.isDisjoint(with: types)
    }

    // MARK: - Actions

    func showPanel() {
        guard isEnabled else { return }
        panel.show()
    }

    /// Puts an item back on the clipboard and moves it to the top.
    func copy(_ item: ClipboardItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(item.text, forType: .string)
        lastChangeCount = pasteboard.changeCount
        record(item.text, sourceBundleID: item.sourceBundleID)
    }

    func remove(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
        save()
    }

    func clear() {
        items.removeAll()
        save()
    }

    /// Adds copied text to the top; copying the same text again moves it up
    /// instead of listing it twice.
    func record(_ text: String, sourceBundleID: String?, at date: Date = .now) {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.utf8.count <= Self.maxTextBytes else { return }
        items.removeAll { $0.text == text }
        items.insert(ClipboardItem(id: UUID(), text: text, copiedAt: date, sourceBundleID: sourceBundleID), at: 0)
        if items.count > Self.maxItems {
            items.removeLast(items.count - Self.maxItems)
        }
        save()
    }

    // MARK: - Monitoring

    private func applyEnabled() {
        if isEnabled {
            startMonitoring()
            if hotKey == nil {
                // ⌃⌘V: unlike ⇧⌘V (Paste and Match Style) or ⌥⌘V (Finder's
                // Move), no common app uses it.
                hotKey = GlobalHotKey(keyCode: UInt32(kVK_ANSI_V), modifiers: UInt32(controlKey | cmdKey)) { [weak self] in
                    self?.panel.toggle()
                }
            }
        } else {
            monitorTask?.cancel()
            monitorTask = nil
            hotKey?.unregister()
            hotKey = nil
            panel.close()
        }
    }

    /// NSPasteboard has no change notification, so poll its change count.
    private func startMonitoring() {
        guard monitorTask == nil else { return }
        // Start from what is on the clipboard now; only later copies are recorded.
        lastChangeCount = NSPasteboard.general.changeCount
        monitorTask = Task { [weak self] in
            while !Task.isCancelled {
                guard let self else { return }
                self.poll()
                try? await Task.sleep(for: .milliseconds(500))
            }
        }
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        guard Self.shouldRecord(types: pasteboard.types ?? []),
              let text = pasteboard.string(forType: .string) else { return }
        record(text, sourceBundleID: NSWorkspace.shared.frontmostApplication?.bundleIdentifier)
    }

    // MARK: - Persistence

    private func load() {
        guard let data = try? Data(contentsOf: storageURL),
              let saved = try? JSONDecoder().decode([ClipboardItem].self, from: data) else { return }
        items = saved
    }

    private func save() {
        let fileManager = FileManager.default
        if items.isEmpty {
            try? fileManager.removeItem(at: storageURL)
            return
        }
        guard let data = try? JSONEncoder().encode(items) else { return }
        try? fileManager.createDirectory(at: storageURL.deletingLastPathComponent(), withIntermediateDirectories: true)
        try? data.write(to: storageURL, options: .atomic)
        // Copied text can be private; keep the file readable by the user only.
        try? fileManager.setAttributes([.posixPermissions: 0o600], ofItemAtPath: storageURL.path)
    }
}
